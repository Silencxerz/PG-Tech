import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const destinations = {
    "MenuView.luau": "game.ServerStorage.GameUIs.Menu.Core.MenuView",
    "MenuController.client.luau": "game.ServerStorage.GameUIs.Menu.Core",
    "Loading.client.luau": "game.ReplicatedFirst.AssetLoader",
    "InterfaceLoader.server.luau": "game.ServerScriptService.NetworkOwnership",
    "DeploymentService.luau": "game.ServerScriptService._0xS0URCEC3X.Plugins.PlayerScripts.PlayerManager",
    "DeploymentBootstrap.server.luau": "game.ServerScriptService.PGDeploymentBootstrap",
};

const sources = await Promise.all(Object.entries(destinations).map(async ([file, destination]) => ({
    file,
    destination,
    source: await readFile(path.join(root, "src", file), "utf8"),
})));

const lines = [
    "-- Generated by tools/build-installer.mjs. Edit the files in src instead.",
    "assert(not game:GetService('RunService'):IsRunning(), 'Stop Play before installing')",
    "local sources = {}",
];
for (const { file, source } of sources) {
    lines.push(`sources[${JSON.stringify(file)}] = ${JSON.stringify(source)}`);
}
lines.push(`
for name, source in pairs(sources) do
    local compiled, message = loadstring(source)
    assert(compiled, name .. ': ' .. tostring(message))
end
local menu = game.ServerStorage.GameUIs.Menu
local core = menu.Core
local loader = game.ReplicatedFirst.AssetLoader
local interfaces = game.ServerScriptService.NetworkOwnership
local service = game.ServerScriptService._0xS0URCEC3X.Plugins.PlayerScripts.PlayerManager
local backup = Instance.new('Folder', game.ServerStorage)
backup.Name = 'PGTechBeforeInstall_' .. os.time()
for _, instance in {menu, loader, interfaces, service} do
    instance:Clone().Parent = backup
end
local view = core:FindFirstChild('MenuView') or Instance.new('ModuleScript', core)
view.Name = 'MenuView'
local bootstrap = game.ServerScriptService:FindFirstChild('PGDeploymentBootstrap')
if bootstrap then bootstrap:Clone().Parent = backup end
bootstrap = bootstrap or Instance.new('Script', game.ServerScriptService)
bootstrap.Name = 'PGDeploymentBootstrap'
`);
for (const { file, destination } of sources) {
    lines.push(`${destination}.Source = sources[${JSON.stringify(file)}]`);
}
lines.push(`
for _, descendant in menu:GetDescendants() do
    if descendant:IsA('LocalScript') then descendant.Disabled = descendant ~= core end
end
for _, descendant in loader:GetDescendants() do
    if descendant:IsA('LocalScript') then descendant.Disabled = true end
end
menu.Main.Visible = false
menu.Disclaimer.Visible = false
menu.Transition.Visible = false
menu.IgnoreGuiInset = true
menu.DisplayOrder = 20
menu.ZIndexBehavior = Enum.ZIndexBehavior.Sibling
menu.ResetOnSpawn = false
game:GetService('ChangeHistoryService'):SetWaypoint('PG Tech interface installed')
print('PG Tech interface installed. Backup: ' .. backup.Name)
`);

await mkdir(path.join(root, "dist"), { recursive: true });
await writeFile(path.join(root, "dist", "Install.luau"), lines.join("\n"), "utf8");
console.log(`Built installer from ${sources.length} source files.`);
